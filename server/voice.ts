import type { DebateConfig } from '../shared/types.ts';
import { EXPRESSION_STYLES, effectiveStyles } from '../shared/styles.ts';

export function voicePrompt(style: DebateConfig['language'], styles?: DebateConfig['styles']) {
  const common = `【说话方式】像一个认真听了对方发言、现在当面接话的真人，而不是在念论文或开会汇报。
优先用“我”“你”“这件事”“说白了”等自然说法。不要每次复述身份或完整辩题，不要固定以“我方认为”开头。避免“综上所述”“不可否认”“从某个维度”“核心命题”“底层逻辑”等模板腔，不给每段加小标题，不堆条目。
少用术语。一个普通人没接触过的概念，立刻换成买菜、上班、外卖、导航、打游戏、合租等生活经验解释；每次最多引入一个必须的专业词。不要把长句和抽象名词连成一堵墙。
可以用一两个短比喻或机智的反问，让人听懂并愿意看下去。比喻要贴合本轮的具体漏洞，不能拿段子替代事实或把类比当成证明；不要每回合硬塞笑话或反复用同一个梗。
【实例与文采】正式辩手的每次发言，优先用一个与当前争点有关的具体生活场景或可靠事例说明：讲清谁、遇到什么处境、为何支持你的判断，不要通篇只说“压力”“结构”“负担”等大词。真实事件须有把握；没有来源的场景用“比如设想”“假设一个家庭”标明是假设，不冒充调查结果，不以一个个案证明普遍规律。可适度引用准确的典故、寓言、诗句或历史故事，并点明它与争点的联系；记不准就不用，不捏造出处，不拿文学修辞替代因果与证据。后续轮次更换有用的例子，避免反复用同一把秤、同一根梁；为实例和收束留足字数。
短段落通常更好读。你可以直接接对方刚说的内容，也可以用例子、陈述或反问来表达，具体结构和结尾由你自主决定，不必每次都按同一种套路开场或收尾。
幽默针对论点，不羞辱对手，不攻击现实人群；不要把“击溃心理防线”等幕后目标直接写进发言。`;
  const selected = effectiveStyles({ language: style, styles }).map(id => EXPRESSION_STYLES.find(s => s.id === id)!);
  return `${common}\n【本场表达偏好，可同时叠加】${selected.map(s => `${s.label}：${s.prompt}`).join('\n')}\n这些是表达偏好，不是人设、思维派别或固定打法；生活化、犀利、幽默、文采与严谨可以同时成立。以准确回应和推进整场争点为先，不必每句话都展示所有风格。`;
}
