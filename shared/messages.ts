import type { Locale } from './locale.ts';

const messageCache = new Map<string, string>();

function interpolate(pattern: string, values: readonly unknown[]): string {
  return pattern.replace(/\{(\d+)\}/g, (_match, index: string) => String(values[Number(index)] ?? ''));
}

const ROLE_NAMES: Readonly<Record<string, string>> = {
  '正方': 'Pro', '反方': 'Con', '裁判': 'Judge', '观众': 'Audience',
  '正方一辩': 'Pro Speaker 1', '正方二辩': 'Pro Speaker 2', '正方三辩': 'Pro Speaker 3',
  '反方一辩': 'Con Speaker 1', '反方二辩': 'Con Speaker 2', '反方三辩': 'Con Speaker 3',
  '按整场表现评分决胜': 'decided by whole-match scoring',
  '完成申诉复核': 'completed the appeal review',
  '确认胜负': 'confirmed the result',
  '申诉与复核已记入档案。': 'The appeal and review are included in the archive.',
};
const REVERSE_ROLES = Object.fromEntries(Object.entries(ROLE_NAMES).map(([zh, en]) => [en, zh]));

function localizeRoles(locale: Locale, values: readonly unknown[]) {
  const roles = locale === 'en' ? ROLE_NAMES : REVERSE_ROLES;
  return values.map(value => typeof value === 'string' ? roles[value] ?? value : value);
}

export function formatMessage(locale: Locale, source: string, values: readonly unknown[]): string {
  return interpolate(locale === 'en' ? EN_MESSAGES[source] ?? source : source, values);
}

function compilePattern(pattern: string, numeric = false) {
  const indices: number[] = [];
  const expression = pattern.split(/(\{\d+\})/).map(part => {
    if (/^\{\d+\}$/.test(part)) {
      indices.push(Number(part.slice(1, -1)));
      return numeric ? '(\\d+(?:\\.\\d+)?)' : '([\\s\\S]*?)';
    }
    return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }).join('');
  return { expression: new RegExp(`^${expression}$`), indices };
}

/** Translate application messages only. User-authored topics and speeches stay verbatim. */
export function translateMessage(locale: Locale, source: string): string {
  const key = `${locale}\0${source}`;
  const cached = messageCache.get(key);
  if (cached !== undefined) return cached;
  let result = locale === 'en' ? EN_MESSAGES[source] : REVERSE_MESSAGES[source];
  if (result === undefined) {
    for (const pattern of MESSAGE_PATTERNS) {
      const candidate = locale === 'en' ? pattern.zh : pattern.en;
      const match = candidate.expression.exec(source);
      if (!match) continue;
      const values: string[] = [];
      candidate.indices.forEach((index, capture) => { values[index] = match[capture + 1]; });
      result = interpolate(locale === 'en' ? pattern.english : pattern.source, localizeRoles(locale, values));
      break;
    }
  }
  result ??= source;
  if (messageCache.size >= 1000) messageCache.clear();
  messageCache.set(key, result);
  return result;
}

